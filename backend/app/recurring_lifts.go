type RecurringLift struct {
	UserID         string                `json:"-" bson:"user_id"`
	ID             string                `json:"-" bson:"_id"`
	Input          RideInput             `json:"route" bson:"route"`
	Schedule       liftschedule.Schedule `json:"schedule" bson:"schedule"`
	Active         bool                  `json:"active" bson:"active"`
	Next           time.Time             `json:"next_departure" bson:"next_departure"`
	Updated        time.Time             `json:"updated_at" bson:"updated_at"`
	Revision       int64                 `json:"revision" bson:"revision"`
	LastOccurrence time.Time             `json:"-" bson:"last_occurrence,omitempty"`
}

var ErrRecurringConflict = errors.New("recurring offer changed")

// An exact replay of the immediately preceding edit is safe after an uncertain
// response. Departure-specific fields are generated by the server, not edits.
func sameRecurringEdit(a, b RecurringLift) bool {
	a.Input.Date, a.Input.Start, a.Input.End, a.Input.Offset = "", "", "", nil
	b.Input.Date, b.Input.Start, b.Input.End, b.Input.Offset = "", "", "", nil
	a.Schedule.Weekdays = slices.Clone(a.Schedule.Weekdays)
	b.Schedule.Weekdays = slices.Clone(b.Schedule.Weekdays)
	slices.Sort(a.Schedule.Weekdays)
	slices.Sort(b.Schedule.Weekdays)
	return a.Active == b.Active && reflect.DeepEqual(a.Input, b.Input) && reflect.DeepEqual(a.Schedule, b.Schedule)
}

type RecurringLiftRepository interface {
	GetRecurringLift(context.Context, string) (RecurringLift, error)
	SaveRecurringLift(context.Context, User, RecurringLift) (RecurringLift, error)
}

func (m mongoUsers) GetRecurringLift(ctx context.Context, user string) (RecurringLift, error) {
	var offer RecurringLift
	err := m.collection.Database().Collection("recurring_lifts").FindOne(ctx, bson.M{"_id": user}).Decode(&offer)
	return offer, err
}
func (m mongoUsers) SaveRecurringLift(ctx context.Context, user User, offer RecurringLift) (RecurringLift, error) {
	next, end, err := offer.Schedule.Next(time.Now().UTC())
	if err != nil {
		return RecurringLift{}, err
	}
	loc, err := time.LoadLocation(offer.Schedule.TimeZone)
	if err != nil {
		return RecurringLift{}, err
	}
	local := next.In(loc)
	_, offset := local.Zone()
	minutes := offset / 60
	// Windows ending at midnight cannot be represented by the ride contract.
	localEnd := end.In(loc)
	if local.Day() != localEnd.Day() {
		return RecurringLift{}, liftschedule.ErrInvalidSchedule
	}
	input := offer.Input
	input.Date = local.Format("2006-01-02")
	input.Start = local.Format("15:04")
	input.End = localEnd.Format("15:04")
	input.Offset = &minutes
	input.Mode = matching.Lift
	input.Driver = true
	if _, err = buildRide(input, user, time.Now().UTC()); err != nil {
		return RecurringLift{}, liftschedule.ErrInvalidSchedule
	}
	offer.UserID = user.ID
	offer.ID = user.ID
	offer.Input = input
	offer.Next = next
	offer.Updated = time.Now().UTC()
	session, err := m.collection.Database().Client().StartSession()
	if err != nil {
		return RecurringLift{}, err
	}
	defer session.EndSession(ctx)
	expectedRevision := offer.Revision
	initialOffer := offer
	_, err = session.WithTransaction(ctx, func(tx context.Context) (any, error) {
		// MongoDB may invoke this callback again after a transient conflict.
		// Rebuild the candidate from the request instead of reusing changes
		// made by an aborted transaction.
		offer = initialOffer
		var current User
		if err := m.collection.FindOne(tx, bson.M{"user_id": user.ID}).Decode(&current); err != nil {
			return nil, err
		}
		if accountRestricted(current) || !current.Onboarded {
			return nil, ErrGroupUnavailable
		}
		if _, err := buildRide(input, current, time.Now().UTC()); err != nil {
			return nil, err
		}
		offers := m.collection.Database().Collection("recurring_lifts")
		var previous RecurringLift
		err := offers.FindOne(tx, bson.M{"_id": user.ID}).Decode(&previous)
		if err != nil && !errors.Is(err, mongo.ErrNoDocuments) {
			return nil, err
		}
		if previous.Revision != expectedRevision {
			if previous.Revision == expectedRevision+1 && sameRecurringEdit(previous, offer) {
				offer = previous
				return nil, nil
			}
			return nil, ErrRecurringConflict
		}
		if _, err := m.collection.UpdateOne(tx, bson.M{"user_id": user.ID}, bson.M{"$inc": bson.M{"safety_version": 1}}); err != nil {
			return nil, err
		}
		offer.Revision = previous.Revision + 1
		offer.LastOccurrence = previous.LastOccurrence
		if !offer.LastOccurrence.IsZero() {
			// A user can edit the time or timezone after a request has already
			// been created. Keep at most one occurrence on that local date.
			last := offer.LastOccurrence.In(loc)
			nextLocal := offer.Next.In(loc)
			sameDate := last.Year() == nextLocal.Year() && last.YearDay() == nextLocal.YearDay()
			if !offer.Next.After(offer.LastOccurrence) || sameDate {
				cutoff := offer.LastOccurrence
				if sameDate {
					cutoff = time.Date(last.Year(), last.Month(), last.Day(), 23, 59, 59, 0, loc)
				}
				next, _, err := offer.Schedule.Next(cutoff)
				if err != nil {
					return nil, err
				}
				offer.Next = next
			}
		}
		_, err = offers.ReplaceOne(tx, bson.M{"_id": user.ID}, offer, options.Replace().SetUpsert(true))
		return nil, err
	})
	return offer, err
}
func (a *AuthDependencies) recurringLift(w http.ResponseWriter, r *http.Request, user User) {
	if _, ok := a.rideStorage(w, user); !ok {
		return
	}
	repo, ok := a.Users.(RecurringLiftRepository)
	if !ok {
		writeJSON(w, 503, map[string]string{"detail": "Recurring lifts unavailable"})
		return
	}
	if r.Method == http.MethodGet {
		offer, err := repo.GetRecurringLift(r.Context(), user.ID)
		if errors.Is(err, mongo.ErrNoDocuments) {
			writeJSON(w, 200, map[string]any{"offer": nil})
			return
		}
		if err != nil {
			writeJSON(w, 503, map[string]string{"detail": "Unable to load offer"})
			return
		}
		writeJSON(w, 200, map[string]any{"offer": offer})
		return
	}
	var offer RecurringLift
	if decodeBody(r, &offer) != nil {
		writeJSON(w, 422, map[string]string{"detail": "Invalid offer"})
		return
	}
	saved, err := repo.SaveRecurringLift(r.Context(), user, offer)
	if err != nil {
		if errors.Is(err, ErrRecurringConflict) {
			writeJSON(w, 409, map[string]string{"detail": "Offer changed. Refresh before saving."})
			return
		}
		if errors.Is(err, liftschedule.ErrInvalidSchedule) {
			writeJSON(w, 422, map[string]string{"detail": "Choose a valid route and daily window"})
			return
		}
		writeJSON(w, 503, map[string]string{"detail": "Unable to save offer"})
		return
	}
	writeJSON(w, 200, map[string]any{"offer": saved})
}

// materializeRecurringLift serializes schedule edits, account restrictions and
// occurrence creation in one transaction. The unique active-ride index remains
// authoritative for concurrent manual requests.
func (m mongoUsers) materializeRecurringLift(ctx context.Context, userID string) error {
	session, err := m.collection.Database().Client().StartSession()
	if err != nil {
		return err
	}
	defer session.EndSession(ctx)
	_, err = session.WithTransaction(ctx, func(tx context.Context) (any, error) {
		now := time.Now().UTC()
		db := m.collection.Database()
		offers := db.Collection("recurring_lifts")
		var offer RecurringLift
		if err := offers.FindOne(tx, bson.M{"_id": userID, "active": true, "next_departure": bson.M{"$lte": now.Add(14 * time.Hour)}}).Decode(&offer); err != nil {
			if errors.Is(err, mongo.ErrNoDocuments) {
				return nil, nil
			}
			return nil, err
		}
		var owner User
		if err := m.collection.FindOne(tx, bson.M{"user_id": userID}).Decode(&owner); err != nil {
			if errors.Is(err, mongo.ErrNoDocuments) {
				_, e := offers.DeleteOne(tx, bson.M{"_id": userID})
				return nil, e
			}
			return nil, err
		}
		if accountRestricted(owner) || !owner.Onboarded {
			_, err := offers.UpdateOne(tx, bson.M{"_id": userID}, bson.M{"$set": bson.M{"active": false, "updated_at": now}})
			return nil, err
		}
		if _, err := m.collection.UpdateOne(tx, bson.M{"user_id": userID}, bson.M{"$inc": bson.M{"safety_version": 1}}); err != nil {
			return nil, err
		}
		state, err := m.Maintenance(tx)
		if err != nil {
			return nil, err
		}
		if state.Enabled {
			_, err := offers.UpdateOne(tx, bson.M{"_id": userID}, bson.M{"$set": bson.M{"next_check": now.Add(time.Minute)}})
			return nil, err
		}
		// If a journey occupies the account, retry until this departure passes. A
		// missed occurrence is advanced, never manufactured retroactively.
		if offer.Next.After(now) {
			count, err := m.rides().CountDocuments(tx, bson.M{"user_id": userID, "status": bson.M{"$in": bson.A{"pending", "matching", "matched"}}})
			if err != nil {
				return nil, err
			}
			if count > 0 {
				_, err = offers.UpdateOne(tx, bson.M{"_id": userID}, bson.M{"$set": bson.M{"next_check": now.Add(time.Minute)}})
				return nil, err
			}
			loc, err := time.LoadLocation(offer.Schedule.TimeZone)
			if err != nil {
				return nil, err
			}
			start := offer.Next.In(loc)
			_, offset := start.Zone()
			minutes := offset / 60
			end := time.Date(start.Year(), start.Month(), start.Day(), offer.Schedule.EndMinute/60, offer.Schedule.EndMinute%60, 0, 0, loc)
			input := offer.Input
			input.Date = start.Format("2006-01-02")
			input.Start = start.Format("15:04")
			input.End = end.Format("15:04")
			input.Offset = &minutes
			input.Mode = matching.Lift
			input.Driver = true
			ride, err := buildRide(input, owner, now)
			if err != nil {
				if !errors.Is(err, errInvalidRide) {
					return nil, err
				}
				_, e := offers.UpdateOne(tx, bson.M{"_id": userID}, bson.M{"$set": bson.M{"active": false, "updated_at": now}})
				return nil, e
			}
			if _, err = m.rides().InsertOne(tx, ride); err != nil {
				return nil, err
			}
			if _, err = offers.UpdateOne(tx, bson.M{"_id": userID}, bson.M{"$set": bson.M{"last_occurrence": offer.Next}}); err != nil {
				return nil, err
			}
		}
		next, _, err := offer.Schedule.Next(maxTime(offer.Next, now))
		if err != nil {
			return nil, err
		}
		_, err = offers.UpdateOne(tx, bson.M{"_id": userID}, bson.M{"$set": bson.M{"next_departure": next, "next_check": next.Add(-14 * time.Hour), "updated_at": now}})
		return nil, err
	})
	return err
}
func maxTime(a, b time.Time) time.Time {
	if a.After(b) {
		return a
	}
	return b
}

func (m mongoUsers) scheduleRecurringLifts(ctx context.Context) error {
	now := time.Now().UTC()
	offers := m.collection.Database().Collection("recurring_lifts")
	cursor, err := offers.Find(ctx, bson.M{"active": true, "next_departure": bson.M{"$lte": now.Add(14 * time.Hour)}, "$or": bson.A{bson.M{"next_check": bson.M{"$lte": now}}, bson.M{"next_check": bson.M{"$exists": false}}}}, options.Find().SetSort(bson.D{{Key: "next_departure", Value: 1}, {Key: "_id", Value: 1}}).SetLimit(50))
	if err != nil {
		return err
	}
	var records []RecurringLift
	err = cursor.All(ctx, &records)
	cursor.Close(ctx)
	if err != nil {
		return err
	}
	var first error
	for _, offer := range records {
		if ctx.Err() != nil {
			return errors.Join(first, ctx.Err())
		}
		if err := m.materializeRecurringLift(ctx, offer.ID); err != nil {
			if first == nil {
				first = err
			}
			// A persistently failing offer must not monopolize the bounded batch.
			// Do not delay a schedule that was edited or advanced in the meantime.
			_, deferErr := offers.UpdateOne(ctx, bson.M{"_id": offer.ID, "revision": offer.Revision, "next_departure": offer.Next, "active": true}, bson.M{"$set": bson.M{"next_check": time.Now().UTC().Add(time.Minute)}})
			if deferErr != nil {
				return errors.Join(first, deferErr)
			}
		}
	}
	return first
}
