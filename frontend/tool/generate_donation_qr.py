"""Generate the donation assets. Tools: qrcode, pillow, zxing-cpp.

The URI was decoded from the owner's supplied QR. Keep its square modules and
four-module quiet zone intact; decoration belongs outside the scannable area.
Run from any directory with the temporary verification environment.
"""
from pathlib import Path
from urllib.parse import parse_qs, urlparse
import json
import qrcode
from PIL import Image
import zxingcpp

ROOT = Path(__file__).resolve().parents[2]
URI = 'upi://pay?pa=christopherjoshy4@okicici&pn=Christopher%20Joshy&aid=uGICAgMC2zu-fJQ'
params = parse_qs(urlparse(URI).query)
assert 'am' not in params, 'Donor chooses the amount in their payment app'
qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, box_size=8, border=4)
qr.add_data(URI)
qr.make(fit=True)
img = qr.make_image(fill_color='black', back_color='white').convert('RGB')
for width in [img.width, 220, 246, 280, 328]:
    sample = img.resize((width, width), Image.Resampling.NEAREST)
    decoded = zxingcpp.read_barcodes(sample)
    assert len(decoded) == 1 and decoded[0].text == URI, f'Decode failed at {width}px'
for target in ['frontend/assets/images/donation-qr.png', 'website/public/art/donation-qr.png']:
    img.save(ROOT / target)
# App and browser launch targets use the same payload as the verified QR.
(ROOT / 'frontend/lib/core/config/donation_config.dart').write_text(
    '// Generated by frontend/tool/generate_donation_qr.py. Public payment destination.\n'
    'class DonationConfig {\n  DonationConfig._();\n'
    f"  static const upi = '{URI}';\n"
    f"  static const payee = '{params['pn'][0]}';\n"
    f"  static const upiId = '{params['pa'][0]}';\n}}\n")
(ROOT / 'website/src/lib/donation-config.ts').write_text(
    '// Generated by frontend/tool/generate_donation_qr.py. Public payment destination.\n'
    f'export const donationUri = {json.dumps(URI)};\n'
    f'export const donationPayee = {json.dumps(params["pn"][0])};\n'
    f'export const donationUpiId = {json.dumps(params["pa"][0])};\n')
print('QR round-trip passed at five sizes; no amount imposed; both assets generated.')
